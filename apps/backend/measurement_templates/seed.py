@transaction.atomic
def seed_system_templates() -> dict[str, MeasurementTemplate]:
    """Create or ensure default system measurement templates exist."""
    specs = [
        (
            "standard-tailoring",
            {
                "name": "Standard Tailoring",
                "category": MeasurementTemplate.Category.TAILORING,
                "description": "Comprehensive upper and lower body tailoring measurements.",
            },
            TAILORING_FIELDS,
        ),
        (
            "standard-shoemaking",
            {
                "name": "Standard Shoemaking (Draft Reference)",
                "category": MeasurementTemplate.Category.SHOEMAKING,
                "description": "Baseline shoemaking foot measurements; confirm field list with practicing shoemakers.",
            },
            SHOEMAKING_FIELDS,
        ),
        (
            "standard-leatherwork",
            {
                "name": "Standard Leatherwork",
                "category": MeasurementTemplate.Category.LEATHERWORK,
                "description": "Custom belts, straps, watch bands, bags, and embossed leather goods.",
            },
            LEATHERWORK_FIELDS,
        ),
    ]

    seeded: dict[str, MeasurementTemplate] = {}
    for slug, defaults, fields in specs:
        template, _ = MeasurementTemplate.objects.get_or_create(
            organization=None,
            slug=slug,
            defaults=defaults,
        )
        version, created = MeasurementTemplateVersion.objects.get_or_create(
            template=template,
            version_number=1,
            defaults={"is_published": True, "changelog": "Initial system template"},
        )
        if created or version.fields.count() == 0:
            for field_spec in fields:
                MeasurementField.objects.get_or_create(
                    template_version=version,
                    key=field_spec["key"],
                    defaults=field_spec,
                )
        seeded[slug] = template
    return seeded
